# Self-test for hooks/guard.py: cases that must be blocked (exit 2) and cases that
# must pass (exit 0). Inputs are wrapped the way Claude Code sends them
# ({"tool_name": "Bash", "tool_input": {"command": ..., "description": ...}}).
# SELFTEST_GUARD=/path/to/copy runs the cases against a modified copy.
H="${SELFTEST_GUARD:-$(dirname "$0")/guard.py}"; pass=0; fail=0
