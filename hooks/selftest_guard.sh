  case "$H" in *.sh) echo "$js" | bash "$H" >/dev/null 2>&1;; *) echo "$js" | python3 "$H" >/dev/null 2>&1;; esac; rc=$?
  if [ "$rc" = "$want" ]; then pass=$((pass+1)); else fail=$((fail+1)); echo "FAIL want $want got $rc: $cmd / $desc"; fi; }

